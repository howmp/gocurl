func NewCookieJar() config.CookieJar {
	return newTrackedCookieJar()
}

func LoadCookieFile(jar config.CookieJar, path string) error {
	data, err := config.ReadLocalFile(path)
	if err != nil {
		return err
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" {
			continue
		}
		httpOnly := false
		if strings.HasPrefix(line, "#HttpOnly_") {
			httpOnly = true
			line = strings.TrimPrefix(line, "#HttpOnly_")
		} else if strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 7 {
			continue
		}
		domain := fields[0]
		pathValue := fields[2]
		if pathValue == "" {
			pathValue = "/"
		}
		secure := strings.EqualFold(fields[3], "TRUE")
		expiresUnix, _ := strconv.ParseInt(fields[4], 10, 64)
		var expires time.Time
		if expiresUnix > 0 {
			expires = time.Unix(expiresUnix, 0)
		}
		host := strings.TrimPrefix(domain, ".")
		cookie := &http.Cookie{
			Name:     fields[5],
			Value:    fields[6],
			Path:     pathValue,
			Secure:   secure,
			HttpOnly: httpOnly,
			Expires:  expires,
		}
		if strings.EqualFold(fields[1], "TRUE") {
			cookie.Domain = domain
		}
		jar.SetCookies(&url.URL{Scheme: "https", Host: host}, []*http.Cookie{cookie})
	}
	return nil
}

func CookieFileTextForHosts(jar config.CookieJar, rawHosts []string) string {
	return cookieFileText(jar, cookieHostSet(rawHosts))
}

func CookieFileTextAll(jar config.CookieJar) string {
	return cookieFileText(jar, nil)
}

func cookieFileText(jar config.CookieJar, hostSet map[string]bool) string {
	var lines []string
	for host, cookies := range jar.GetAllCookies() {
		cookieHost := normalizeCookieHost(host)
		for _, cookie := range cookies {
			hostOnly := cookie.Domain == ""
			domain := normalizeCookieHost(cookie.Domain)
			if hostOnly {
				domain = cookieHost
			}
			if hostSet != nil && !cookieMatchesHost(domain, hostOnly, hostSet) {
				continue
			}
			if !validExportCookie(domain, hostOnly, cookie) {
				continue
			}
			includeSubdomains := "TRUE"
			if hostOnly {
				includeSubdomains = "FALSE"
			} else if !strings.HasPrefix(domain, ".") {
				domain = "." + domain
			}
			secure := "FALSE"
			if cookie.Secure {
				secure = "TRUE"
			}
			expiry := int64(0)
			if !cookie.Expires.IsZero() {
				expiry = cookie.Expires.Unix()
			}
			pathValue := cookie.Path
			if pathValue == "" {
				pathValue = "/"
			}
			prefix := ""
			if cookie.HttpOnly {
				prefix = "#HttpOnly_"
			}
			lines = append(lines, fmt.Sprintf("%s%s\t%s\t%s\t%s\t%d\t%s\t%s",
				prefix, domain, includeSubdomains, pathValue, secure, expiry, cookie.Name, cookie.Value))
		}
	}
	sort.Strings(lines)
	var b strings.Builder
	b.WriteString("# Netscape HTTP Cookie File\n")
	b.WriteString("# This file was generated by gocurl.\n\n")
	for _, line := range lines {
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.String()
}

func cookieHostSet(rawHosts []string) map[string]bool {
	set := make(map[string]bool)
	for _, raw := range rawHosts {
		u, err := NormalizeURL(raw)
		if err != nil {
			continue
		}
		switch u.Scheme {
		case "http", "https", "ws", "wss":
		default:
			continue
		}
		if host := normalizeCookieHost(u.Hostname()); host != "" {
			set[host] = true
		}
	}
	return set
}

func normalizeCookieHost(host string) string {
	host = strings.ToLower(strings.TrimSpace(host))
	host = strings.TrimPrefix(host, ".")
	if h, _, err := net.SplitHostPort(host); err == nil {
		host = h
	}
	return strings.Trim(host, "[]")
}

func cookieMatchesHost(domain string, hostOnly bool, hostSet map[string]bool) bool {
	domain = strings.TrimPrefix(domain, ".")
	if domain == "" {
		return false
	}
	for target := range hostSet {
		if hostOnly {
			if domain == target {
				return true
			}
			continue
		}
		if domain == target || strings.HasSuffix(target, "."+domain) {
			return true
		}
	}
	return false
}

func SaveCookieFile(jar config.CookieJar, path string, stdout io.Writer) error {
	text := CookieFileTextAll(jar)
	if path == "-" {
		_, err := io.WriteString(stdout, text)
		return err
	}
	if err := output.WriteFile(path, []byte(text)); err != nil {
		return &exitcode.WriteError{Err: err}
	}
	return nil
}

func validExportCookie(domain string, hostOnly bool, cookie *http.Cookie) bool {
	if cookie == nil || hasCookieControl(cookie.Name) || hasCookieControl(cookie.Value) || hasCookieControl(cookie.Path) {
		return false
	}
	if hostOnly {
		return domain != ""
	}
	domain = strings.TrimPrefix(domain, ".")
	if domain == "" {
		return false
	}
	publicSuffix, _ := publicsuffix.PublicSuffix(domain)
	return publicSuffix != domain
}

func CookieHeaderForURL(jar config.CookieJar, u *url.URL) string {
	if jar == nil || u == nil {
		return ""
	}
	cookies := jar.Cookies(u)
	parts := make([]string, 0, len(cookies))
	for _, cookie := range cookies {
		parts = append(parts, cookie.Name+"="+cookie.Value)
	}
	return strings.Join(parts, "; ")
}
